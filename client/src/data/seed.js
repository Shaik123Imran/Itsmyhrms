function timesheetEntry({
  id,
  employeeId,
  employeeName,
  offset,
  project,
  task,
  hours,
  status,
}) {
  const dateISO = isoOffset(offset)
  return {
    id,
    employeeId,
    employeeName,
    date: formatDate(dateISO),
    dateISO,
    project,
    task,
    hours,
    status,
  }
}

